// Paste into the DevTools console on https://www.instagram.com while logged in.
// Prints the .env lines for this project and copies them to your clipboard.
// Paste the result into the project's root .env file (it's gitignored).
//
// To add a new variable later: add one entry to VARS below, and the same key
// to .env.example. Entry fields:
//   key      - env var name the Python scripts read
//   cookie   - cookie name to read from document.cookie
//   httpOnly - true if the browser hides it from JS (copy it by hand from
//              DevTools > Application > Cookies; it's printed as a blank line to fill in)
//   get      - custom function returning the value, for anything that isn't a cookie
(() => {
  const VARS = [
    { key: "IG_SESSIONID", cookie: "sessionid", httpOnly: true },
    { key: "IG_CSRFTOKEN", cookie: "csrftoken" },
    { key: "IG_DS_USER_ID", cookie: "ds_user_id" },
  ];

  if (!location.hostname.endsWith("instagram.com")) {
    return console.error("Run this on https://www.instagram.com");
  }

  const readCookie = (name) =>
    document.cookie.match(new RegExp(`(?:^|; )${name}=([^;]*)`))?.[1];

  const lines = [`# generated by tools/get_env.js on ${new Date().toISOString()}`];
  const manual = [];
  for (const v of VARS) {
    if (v.httpOnly) {
      lines.push(`${v.key}=`);
      manual.push(`${v.key}  <-  cookie "${v.cookie}"`);
      continue;
    }
    const value = v.get ? v.get() : readCookie(v.cookie);
    if (!value) console.warn(`${v.key}: not found (are you logged in?)`);
    lines.push(`${v.key}=${value ?? ""}`);
  }

  const text = lines.join("\n");
  console.log(text);
  if (manual.length) {
    console.log(
      "Fill these in by hand from DevTools > Application > Cookies > https://www.instagram.com:\n  " +
        manual.join("\n  ")
    );
  }
  try {
    copy(text); // DevTools-only helper
    console.log("Copied to clipboard.");
  } catch {}
})();
